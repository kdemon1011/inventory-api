"""
OpenEnv HTTP/WebSocket Server for the Inventory Environment.

This file uses OpenEnv's create_app() to auto-generate ALL server routes:
  - POST /reset        → Reset the environment
  - POST /step         → Execute an action
  - GET  /state        → Get current state
  - GET  /health       → Health check
  - WebSocket /ws      → Persistent WebSocket connection
  - GET  /schema       → Action/Observation JSON schemas
  - GET  /             → Web UI (auto-generated by OpenEnv!)

Instead of manually defining 7+ routes like we did before,
create_app() does it ALL in ONE line.

Usage:
    # Start the server:
    cd /home/kdemon/Clients/huzzle/inventory-api
    python server/app.py

    # Or with uvicorn directly:
    uvicorn server.app:app --host 0.0.0.0 --port 9000
"""

from typing import Any, Dict, Union

from pydantic import TypeAdapter

# Support both in-repo and standalone imports
try:
    from openenv.core.env_server.http_server import create_app
    from openenv.core.env_server.mcp_types import (
        CallToolAction,
        CallToolObservation,
        ListToolsAction,
    )
    from openenv.core.env_server.types import Action
    from .inventory_environment import InventoryEnvironment
except ImportError:
    from openenv.core.env_server.http_server import create_app
    from openenv.core.env_server.mcp_types import (
        CallToolAction,
        CallToolObservation,
        ListToolsAction,
    )
    from openenv.core.env_server.types import Action

    import sys
