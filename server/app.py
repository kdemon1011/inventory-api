# ── Discriminated Union for MCP Actions ──
# The MCPToolClient sends both ListToolsAction and CallToolAction via the
# same WebSocket "step" channel.  OpenEnv's server calls
#   action_cls.model_validate(data)
# to deserialise the incoming message.  If we pass only CallToolAction,
# ListToolsAction messages cause a ValidationError.
#
# Solution: create a thin wrapper class whose model_validate() uses a
# Pydantic TypeAdapter to automatically dispatch to the right concrete
# Action subclass based on the "type" discriminator field.
_mcp_action_adapter = TypeAdapter(Union[ListToolsAction, CallToolAction])


class MCPAction(Action):
    """Discriminated-union action that deserialises to the correct MCP action."""

    @classmethod
    def model_validate(cls, data: Any, **kwargs: Any) -> Action:  # type: ignore[override]
        if isinstance(data, dict):
            return _mcp_action_adapter.validate_python(data)
        return _mcp_action_adapter.validate_python(data)


# ── THIS IS THE KEY LINE ──
# create_app() generates the ENTIRE FastAPI application automatically:
# - HTTP endpoints (/reset, /step, /state, /health, /schema)
# - WebSocket endpoint (/ws) for persistent connections
# - Web UI for interactive testing
# - Swagger/OpenAPI docs
#
# Arguments:
#   InventoryEnvironment  → Your environment CLASS (not instance!)
#   MCPAction             → Discriminated union so BOTH list_tools AND call_tool work
#   CallToolObservation   → The observation type (MCP tool results)
#   env_name              → Name shown in the UI and docs
app = create_app(
    InventoryEnvironment,
    MCPAction,
    CallToolObservation,
    env_name="inventory_env",
)


def main():
    """
    Entry point for direct execution.

    Starts the OpenEnv server on the configured OPENENV_PORT (default 9000).
    Make sure the Inventory API is already running on API_PORT (default 8000).
    """
    import uvicorn
    from config import OPENENV_PORT
    uvicorn.run(app, host="0.0.0.0", port=OPENENV_PORT)


if __name__ == "__main__":
    main()
